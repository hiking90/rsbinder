    /// Records what [`death_signal`] does; `unlink_panics` models a poisoned `recipients` lock.
    struct FakeRemote {
        link: Option<StatusCode>,
        unlink_panics: bool,
        unlinked: AtomicUsize,
        recipient: Mutex<Option<std::sync::Weak<dyn DeathRecipient>>>,
    }

    impl FakeRemote {
        fn new(link: Option<StatusCode>, unlink_panics: bool) -> Arc<Self> {
            Arc::new(Self {
                link,
                unlink_panics,
                unlinked: AtomicUsize::new(0),
                recipient: Mutex::new(None),
            })
        }

        /// Deliver an obituary as a worker thread does: via the stored recipient, only a `Weak`.
        fn fire_obituary(self: &Arc<Self>, who: &WIBinder) {
            // Only the test's handle left: like a destroyed proxy, no subscription remains.
            assert!(Arc::strong_count(self) > 1, "the signal dropped its binder");
            let recipient = self
                .recipient
                .lock()
                .unwrap_or_else(|e| e.into_inner())
                .clone();
            let recipient = recipient.expect("no recipient registered").upgrade();
            recipient
                .expect("the signal dropped its recipient")
                .binder_died(who);
        }

        fn unlink_count(&self) -> usize {
            self.unlinked.load(Ordering::SeqCst)
        }
    }

    impl IBinder for FakeRemote {
        fn link_to_death(
            &self,
            recipient: std::sync::Weak<dyn DeathRecipient>,
        ) -> crate::Result<()> {
            if let Some(err) = self.link {
                return Err(err);
            }
            *self.recipient.lock().unwrap_or_else(|e| e.into_inner()) = Some(recipient);
            Ok(())
        }
        fn unlink_to_death(
            &self,
            recipient: std::sync::Weak<dyn DeathRecipient>,
        ) -> crate::Result<()> {
            assert!(!self.unlink_panics, "injected unlink panic");
            // Match by `Weak::ptr_eq` like the real proxy: a wrong-recipient unlink must not count.
            let mut slot = self.recipient.lock().unwrap_or_else(|e| e.into_inner());
            if !slot
                .as_ref()
                .is_some_and(|stored| std::sync::Weak::ptr_eq(stored, &recipient))
            {
                return Err(StatusCode::NameNotFound);
            }
            *slot = None;
            self.unlinked.fetch_add(1, Ordering::SeqCst);
            Ok(())
        }
        fn ping_binder(&self) -> crate::Result<()> {
            Ok(())
        }
        fn as_any(&self) -> &dyn std::any::Any {
            self
        }
        fn as_transactable(&self) -> Option<&dyn crate::Transactable> {
            None
        }
        fn descriptor(&self) -> &str {
            "rsbinder.test.IFakeRemote"
        }
        fn is_remote(&self) -> bool {
            true
        }
        fn stability(&self) -> Stability {
            Stability::default()
        }
    }

    /// Poll once without a runtime; a real one would only add a way for the test to hang.
    fn poll_once(signal: &mut DeathSignal) -> Poll<()> {
        let mut cx = Context::from_waker(std::task::Waker::noop());
        Pin::new(signal).poll(&mut cx)
    }

