//! This module lets you use the Tokio `spawn_blocking` pool with AIDL in async
//! Rust code (enabled by the default `tokio` feature).
//!
//! It works by defining a type [`Tokio`], which you use as the generic
//! parameter `P` of the `IFooAsync<P>` trait generated by the AIDL compiler.
//! Obtain an async proxy either with the crate-root [`try_get_interface_async`] helper,
//! or by upgrading a sync handle with [`Strong::into_async`]:
//!
//! ```text
//! use rsbinder::Tokio;
//!
//! // Look up a service and cast straight to its async interface; `None` if not registered.
//! let svc = rsbinder::try_get_interface_async::<dyn SomeAsyncInterface<Tokio>>("name").await?;
//!
//! // Or upgrade an existing sync Strong handle:
//! let svc_async = sync_handle.into_async::<Tokio>();
//! ```
//!
//! [`Tokio`]: crate::Tokio
//! [`try_get_interface_async`]: crate::try_get_interface_async
//! [`Strong::into_async`]: crate::Strong::into_async

use crate::{
    hub, BinderAsyncPool, BinderAsyncRuntime, BinderResult, BoxFuture, DeathRecipient, FromIBinder,
    SIBinder, StatusCode, Strong, WIBinder,
};
use std::future::Future;
use std::pin::Pin;
use std::sync::{Arc, Mutex};
use std::task::{Context, Poll};

/// A `spawn_blocking` failure as a status; a panic resumes (none on Android: `panic = abort`).
pub(crate) fn join_error_status(e: tokio::task::JoinError) -> StatusCode {
    if e.is_panic() {
        std::panic::resume_unwind(e.into_panic());
    }
    if e.is_cancelled() {
        StatusCode::FailedTransaction
    } else {
        StatusCode::Unknown
    }
}

/// Retrieve an existing service for a particular interface — a `getService`
/// call and the interface check after it, neither of which waits — the awaitable counterpart
/// of [`crate::hub::try_get_interface`], with its result: `Ok(None)` when the
/// name is not registered, the service manager's [`Status`](crate::Status) on a failure.
/// For an event-driven wait use [`wait_for_interface_async`]; for a lookup
/// that will not start an unregistered lazy service,
/// [`check_interface_async`] (except on Android 15 r6+, where `check_*` is
/// carried by `getService` too — see the `hub` module doc).
///
/// The `_async` suffix is what separates the crate root's awaitable lookups
/// from the synchronous ones in [`crate::hub`]. It matches
/// [`crate::connect_async`], the facade entry point.
///
/// Called while handling a transaction
/// ([`is_handling_transaction`](crate::is_handling_transaction)), the lookup
/// and the interface check run **inline** on the handler's thread, as every
/// async API of this crate does there (see [`BinderAsyncPool`]'s *Which
/// thread a transact runs on*), and need no Tokio runtime; elsewhere they run
/// on the blocking pool. Inside a handler this is also the bounded way to wait
/// for a name: loop over it with a `tokio::time::sleep` between tries, under a
/// `timeout` (see [`wait_for_interface_async`]'s *From inside a transaction*).
pub async fn try_get_interface_async<T: FromIBinder + ?Sized + 'static>(
    name: &str,
) -> BinderResult<Option<Strong<T>>> {
    let name = name.to_string();
    blocking_op(move || hub::try_get_interface::<T>(&name)).await
}

/// Run the blocking binder work of an async API of this crate through
/// [`crate::__spawn_transact`]: inline on a thread that is handling a
/// transaction, on the Tokio blocking pool otherwise. Every async lookup and
/// [`crate::connect_async`] go through here, so the choice is made in one
/// place; `rsbinder/tests/source_invariants.rs` pins the `spawn_blocking`,
/// `is_handling_transaction` and pool `::spawn(` sites that would bypass it.
pub(crate) fn blocking_op<B, E, F>(op: F) -> BoxFuture<'static, Result<B, E>>
where
    F: FnOnce() -> Result<B, E> + Send + 'static,
    B: Send + 'static,
    E: From<StatusCode> + Send + 'static,
{
    crate::__spawn_transact::<Tokio, _, _, _, _, _, _>(op, |res| async move { res })
}

/// [`try_get_interface_async`] with "not registered" folded into
/// [`StatusCode::NameNotFound`] and the [`Status`](crate::Status) into its [`StatusCode`].
#[deprecated(
    since = "0.13.0",
    note = "use `try_get_interface_async`, which returns `Ok(None)` for a name that is not \
            registered, as `hub::try_get_interface` does"
)]
pub async fn get_interface_async<T: FromIBinder + ?Sized + 'static>(
    name: &str,
) -> Result<Strong<T>, StatusCode> {
    try_get_interface_async::<T>(name)
        .await?
        .ok_or(StatusCode::NameNotFound)
}

/// Wait until the service named `name` is registered, then cast it to `T` —
/// the awaitable counterpart of [`crate::hub::wait_for_interface`] (AOSP
/// `binder_tokio::wait_for_interface`).
///
/// The contract is the synchronous one: the wait is **unbounded**, it resolves
/// as soon as the service appears, and it gives up with
/// [`StatusCode::NameNotFound`] only when the service manager is unreachable
/// or refuses `registerForNotifications` for `name` (an invalid name, an
/// SELinux `find` denial); a [`hub::default`] failure is returned as is. A
/// name registered under a different interface is
/// [`StatusCode::BadType`], exactly as in the sync path — the wait is not
/// retried on a descriptor mismatch.
///
/// Called while handling a transaction, the whole wait runs inline on the
/// handler's thread instead, and the first poll returns only when it ends (see
/// *From inside a transaction*). What *Dropping the future*, *Cost* and *What
/// drives it* say about the blocking pool is about a call made anywhere else.
///
/// # Dropping the future
///
/// Dropping it ends the wait: the drop marks it cancelled, the thread carrying
/// the wait leaves its condvar at once, and on its way out it unregisters the
/// callback it had registered with the service manager. That is what makes it
/// usable as one arm of a `select!` or under a `timeout`. Nothing is left
/// behind on the service manager — but the unregister is a wire call made
/// after the drop returns, so a caller that re-registers the same name
/// immediately can still see the old callback counted.
///
/// Shutting the runtime down counts as dropping it — which matters, because
/// `Runtime::drop` waits for blocking tasks: a wait that could not be
/// cancelled would hold the shutdown open for as long as the service stayed
/// unregistered.
///
/// # Cost
///
/// One thread of the Tokio **blocking pool** for as long as the wait lasts. The
/// pool is the same one every outbound binder call goes through, so a process
/// that parks many simultaneous waits there reduces what is left for calls;
/// service startup waits (a handful, at process start) are what this is for.
///
/// # What drives it
///
/// The wait is a single `spawn_blocking` task, and the blocking pool runs
/// independently of any scheduler: `onRegistration` arriving on a binder thread
/// and waking that task's condvar, and the per-second `getService` re-poll,
/// both proceed whatever the runtime is doing. What the runtime decides is how
/// this future — the handle to that task — is driven:
///
/// | How this future is driven | Completion | A `timeout` around it |
/// |---|---|---|
/// | awaited on a runtime that is being driven | observed | fires |
/// | polled on a thread handling a transaction (a kernel binder or RPC transaction's handler, with or without a Tokio runtime) | the first poll runs the whole wait inline and returns its result | never — see *From inside a transaction* |
/// | polled in a local async service called in-process through its sync handle (`Bn*::new_async_binder`) from a thread that handles no transaction | on the blocking pool, as in the first row | fires while the runtime the [`TokioRuntime`] handle points at runs its timer |
/// | `tokio::spawn`ed onto a current-thread runtime nobody is parked in | never — the task is not polled, so the wait never starts and no pool thread is taken | – |
///
/// The first poll is what submits the blocking task, so a runtime that stops
/// being driven afterwards leaves the wait holding its pool thread and polling
/// the service manager every second, with nobody there to take the result.
///
/// # From inside a transaction
///
/// Called while handling a transaction
/// ([`is_handling_transaction`](crate::is_handling_transaction)), the whole
/// operation — the wait, the lookups it re-polls with, and the interface check
/// after it — runs **inline** on the handler's thread, as every async API of
/// this crate does there (see [`BinderAsyncPool`]'s *Which thread a transact
/// runs on*) and as AOSP `binder_tokio::wait_for_interface` does. It needs no
/// Tokio runtime. Every call it makes stays in the handler's transaction
/// chain, so the kernel can hand it to a peer thread that waits for this
/// handler's reply. That covers the interface check's `INTERFACE_TRANSACTION`
/// to the service found and, on the Android 16 protocol with the `rpc` feature,
/// the calls to a service's accessor; made from a pool thread, they would
/// never be answered by a peer whose binder threads all wait for this handler
/// and whose thread pool cannot grow.
///
/// The cost is that only the wait's own end ends it. The first poll returns
/// once the service appears or the wait gives up, so a `timeout`, a `select!`
/// or a drop around the future never takes effect, and the handler's binder
/// thread and its caller's reply stay held until then — for good, if the name
/// is never registered. Look services up before serving, not while serving.
/// For a bounded wait inside a handler, loop over [`try_get_interface_async`]
/// with a `tokio::time::sleep` between tries, under the `timeout`: each try is
/// bounded and runs inline, and the sleep needs a runtime whose timer advances
/// (see [`TokioRuntime`]'s *Stalls*). A loop over [`check_interface_async`]
/// does not do this: `checkService` never starts a lazy service, which
/// registers only once something calls `getService` for it.
///
/// # Thread pool
///
/// A binder thread pool ([`crate::ProcessState::start_thread_pool`]) is what
/// makes the wait event-driven; without one it degrades to the ~1s re-poll,
/// exactly as the synchronous path does.
pub async fn wait_for_interface_async<T: FromIBinder + ?Sized + 'static>(
    name: &str,
) -> Result<Strong<T>, StatusCode> {
    // Outside the closure: the drop guard must reach the wait's condvar after this future ends.
    let state = Arc::new(hub::WaiterState::default());
    let _cancel = CancelWaitOnDrop(state.clone());

    let name = name.to_string();
    let wait_state = state.clone();
    blocking_op(move || {
        // `hub::default()` may probe the wire; casting here matches the sync path's `BadType`.
        let binder = hub::default()?
            .wait_for_service_cancellable(&name, wait_state)
            .map_err(|end| {
                end.log(&name);
                StatusCode::NameNotFound
            })?;
        binder.into_interface_checked()
    })
    .await
}

/// Cancels the wait on drop: a `spawn_blocking` task ignores `abort()`, so its state tells it.
struct CancelWaitOnDrop(Arc<hub::WaiterState>);

impl Drop for CancelWaitOnDrop {
    fn drop(&mut self) {
        self.0.cancel();
    }
}

/// Resolve `name` if it is registered **now**, without waiting — the awaitable
/// counterpart of [`crate::hub::check_interface`].
///
/// [`StatusCode::NameNotFound`] when the name is not registered. Unlike
/// [`try_get_interface_async`] this will not start an unregistered lazy service,
/// except on Android 15 r6+, where `check_*` is carried by `getService` —
/// see the `hub` module doc.
///
/// Called while handling a transaction
/// ([`is_handling_transaction`](crate::is_handling_transaction)), the lookup
/// and the interface check run **inline** on the handler's thread, as every
/// async API of this crate does there (see [`BinderAsyncPool`]'s *Which
/// thread a transact runs on*), and need no Tokio runtime; elsewhere they run
/// on the blocking pool.
pub async fn check_interface_async<T: FromIBinder + ?Sized + 'static>(
    name: &str,
) -> Result<Strong<T>, StatusCode> {
    let name = name.to_string();
    blocking_op(move || hub::check_interface::<T>(&name)).await
}

/// A future that completes when a binder dies — one `select!` arm instead of a
/// [`DeathRecipient`] implementation.
///
/// Obtained from [`death_signal`]. Completes with `()`; there is nothing to
/// report beyond the death itself, and the binder it watches is the one that
/// was passed in.
///
/// It is fused: once it has completed, polling it again returns
/// [`Poll::Ready`] immediately instead of panicking. That matters because the
/// future is [`Unpin`], so a `select!` arm written as `_ = &mut died` can be
/// polled after the death has already been reported.
///
/// Fused means *always ready*, not *ignored*: after the death, a `select!` arm
/// holding `&mut signal` is ready on every iteration, so a loop that keeps
/// selecting on it runs that arm over and over and makes no other progress.
/// Leave the loop from that arm, or disable it once it has fired — `select!`
/// takes a per-arm precondition for exactly this:
/// `_ = &mut died, if !dead => { dead = true; … }`.
///
/// Dropping it before the death unregisters the notification.
///
/// Dropping it never panics. The kernel `unlink_to_death` panics on a
/// poisoned recipients lock, which any earlier panic under that lock leaves
/// behind. The unlink therefore runs under `catch_unwind` (as
/// `bridge::unlink_all` does); a caught panic is logged and leaves the death
/// link registered.
#[must_use = "dropping the signal at once unregisters the death notification at once"]
pub struct DeathSignal {
    rx: tokio::sync::oneshot::Receiver<()>,
    /// Strong: the link keeps only a `Weak`, so without this the notification would never fire.
    recipient: Arc<SignalRecipient>,
    /// Strong: the proxy owns the subscription; if the caller drops it, a weak ref pends forever.
    binder: SIBinder,
    /// `false` for an already-dead binder, which never got a link to undo.
    linked: bool,
    /// Set once `rx` has yielded: a `oneshot` receiver panics if polled again (see "fused").
    fired: bool,
}

/// [`DeathRecipient`] that does nothing but wake a [`DeathSignal`].
struct SignalRecipient(Mutex<Option<tokio::sync::oneshot::Sender<()>>>);

impl SignalRecipient {
    fn fire(&self) {
        // `send` consumes the sender: only the first firing sends, a spurious second is dropped.
        if let Some(tx) = self.0.lock().unwrap_or_else(|e| e.into_inner()).take() {
            let _ = tx.send(());
        }
    }
}

impl DeathRecipient for SignalRecipient {
    fn binder_died(&self, _who: &WIBinder) {
        // Binder or RPC session thread; a `oneshot` send takes no binder-stack lock.
        self.fire();
    }
}

impl Future for DeathSignal {
    type Output = ();

    fn poll(self: Pin<&mut Self>, cx: &mut Context<'_>) -> Poll<()> {
        let this = self.get_mut();
        if this.fired {
            return Poll::Ready(());
        }
        // `Err(RecvError)` can't occur while we hold the recipient; resolving beats hanging.
        match Pin::new(&mut this.rx).poll(cx) {
            Poll::Ready(_) => {
                this.fired = true;
                Poll::Ready(())
            }
            Poll::Pending => Poll::Pending,
        }
    }
}

impl Drop for DeathSignal {
    fn drop(&mut self) {
        if !self.linked {
            return;
        }
        // Unlink may panic (see `DeathSignal` doc); a panic out of `Drop` mid-unwind aborts.
        let unlink = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
            self.binder.unlink_to_death_arc(&self.recipient)
        }));
        match unlink {
            Ok(Ok(())) => {}
            // Expected once the obituary has been delivered.
            Ok(Err(err)) => log::debug!("DeathSignal: unlink_to_death returned {err:?}"),
            Err(_) => {
                log::error!("DeathSignal: unlink_to_death panicked; a death link stays registered")
            }
        }
    }
}

impl std::fmt::Debug for DeathSignal {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("DeathSignal")
            .field("linked", &self.linked)
            .field("fired", &self.fired)
            .finish_non_exhaustive()
    }
}

/// Watch `binder` and complete when it dies.
///
/// ```ignore
/// let svc = rsbinder::wait_for_interface_async::<dyn IFooAsync<Tokio>>("foo").await?;
/// let died = rsbinder::death_signal(&svc.as_binder())?;
/// tokio::select! {
///     r = svc.work() => r?,
///     _ = died => return Err(/* the service is gone */),
/// }
/// ```
///
/// An **already dead** binder is not an error: the answer to "wait until it
/// dies" is available immediately, so the returned future is already complete.
///
/// # Errors
///
/// - [`StatusCode::InvalidOperation`] for a local binder (`Binder<T>` does not
///   support death notification — there is no remote process to lose).
/// - [`StatusCode::InvalidOperation`] for an RPC proxy whose session nothing
///   serves (see *Requirements*).
/// - Whatever registering the notification reports otherwise.
///
/// # Requirements
///
/// - **Kernel binder:** the obituary is delivered by a thread reading the
///   driver, so the process needs a thread pool
///   ([`crate::ProcessState::start_thread_pool`]) or a thread inside a
///   transaction. A pure client with neither never observes the death, and this
///   future stays pending — the same condition as
///   [`crate::SIBinder::link_to_death_arc`].
/// - **RPC:** death is the session's connection dropping, so the session has to
///   be served (`spawn_serve`/`serve_blocking`, or a client with incoming
///   connections); otherwise the link is refused with
///   [`StatusCode::InvalidOperation`].
pub fn death_signal(binder: &SIBinder) -> Result<DeathSignal, StatusCode> {
    let (tx, rx) = tokio::sync::oneshot::channel();
    let recipient = Arc::new(SignalRecipient(Mutex::new(Some(tx))));

    match binder.link_to_death_arc(&recipient) {
        Ok(()) => Ok(DeathSignal {
            rx,
            recipient,
            binder: binder.clone(),
            linked: true,
            fired: false,
        }),
        // Already dead (both stacks answer `DeadObject` after the obituary): completed signal.
        Err(StatusCode::DeadObject) => {
            recipient.fire();
            Ok(DeathSignal {
                rx,
                recipient,
                binder: binder.clone(),
                linked: false,
                fired: false,
            })
        }
        Err(err) => Err(err),
    }
}

/// Use the Tokio `spawn_blocking` pool with AIDL.
///
/// [`spawn`](BinderAsyncPool::spawn) always hands the work to
/// `tokio::task::spawn_blocking`; a generated proxy and every async API of
/// this crate keep the work of a call made inside a transaction on the
/// handler's thread themselves (see [`BinderAsyncPool`]).
pub enum Tokio {}

impl BinderAsyncPool for Tokio {
    fn spawn<'a, F1, F2, Fut, A, B, E>(spawn_me: F1, after_spawn: F2) -> BoxFuture<'a, Result<B, E>>
    where
        F1: FnOnce() -> A,
        F2: FnOnce(A) -> Fut,
        Fut: Future<Output = Result<B, E>>,
        F1: Send + 'static,
        F2: Send + 'a,
        Fut: Send + 'a,
        A: Send + 'static,
        B: Send + 'a,
        E: From<crate::StatusCode>,
    {
        let handle = tokio::task::spawn_blocking(spawn_me);
        Box::pin(async move {
            match handle.await {
                Ok(res) => after_spawn(res).await,
                Err(e) => Err(join_error_status(e).into()),
            }
        })
    }
}

/// Wrapper around a Tokio [`Handle`], for providing a runtime to a binder
/// server.
///
/// An async server implementation is driven by [`BinderAsyncRuntime::block_on`]
/// on whatever thread delivered the transaction — a kernel binder looper, or an
/// RPC session thread. Those threads are outside the runtime, which is the case
/// `Handle::block_on` is built for.
///
/// The same `block_on` is also reached from a *synchronous* handle to a local
/// async service: `Bn*::new_async_binder` returns `Strong<dyn IFoo>`, whose
/// generated wrapper implements each sync method as `block_on(inner.method())`.
/// Calling that handle from a task on a multi-threaded runtime would otherwise
/// panic with "Cannot start a runtime from within a runtime", so this impl
/// releases the worker's core with [`tokio::task::block_in_place`] first.
///
/// Two independent things then decide what the call does, and reading them as
/// one list is how the failures get misattributed. **Where the call is made
/// from** decides whether it runs at all. **Which runtime the handle points at**
/// decides whether the future can finish. Either answer holds whatever the other
/// one is.
///
/// # Panics
///
/// Where the call is made from, whatever the handle points at. Tokio refuses a
/// `Handle::block_on` on a thread that is already executing inside a runtime,
/// and [`block_in_place`] — which steps back out of one — exists only for the
/// multi-threaded runtime. That is the whole rule:
///
/// | The calling thread | Result |
/// |---|---|
/// | Not executing inside a runtime | runs |
/// | Inside a **multi-threaded** runtime | runs — releasing the core first when the caller is a worker holding one, inline otherwise |
/// | Inside a multi-threaded runtime, within a [`LocalSet`] | **panic** — "can call blocking only when running on the multi-threaded runtime"; `block_in_place` is refused there |
/// | Inside a **current-thread** runtime | **panic** — "Cannot start a runtime from within a runtime"; there is no way back out |
///
/// Reading a position off that rule is the part worth doing carefully, because
/// "inside a runtime" is not the same as "on a runtime's thread":
///
/// - A `spawn_blocking` pool thread is **outside** the runtime it belongs to,
///   for either flavor. Those calls run.
/// - A `Runtime::block_on` body is **inside** — so a current-thread runtime's
///   `Runtime::block_on` body is the last row, not the first.
/// - **A handler this adapter is already driving is inside**, for as long as
///   `block_on` is driving it, and inside *the handle's* runtime whatever thread
///   it started on. So a service whose `TokioRuntime` holds a current-thread
///   handle cannot reach a second local service through a sync handle from
///   within a handler — that nested call is the last row. Reach it with
///   [`Strong::into_async`] instead, or drive the service from a
///   multi-threaded handle.
///
/// [`block_in_place`]: tokio::task::block_in_place
///
/// # Stalls
///
/// Which runtime the handle points at. This decides completion whatever the
/// caller.
///
/// `Handle::block_on` polls the future on the **calling** thread — not on a
/// worker — for either flavor, and that is all it does. Anything the handler
/// needs that runtime's *scheduler* to advance — a timer, IO readiness, or a
/// [`tokio::spawn`]ed task — needs that runtime to be running:
///
/// - A **multi-threaded** runtime always is: its workers drive the timer and IO
///   drivers and run spawned tasks.
/// - A **current-thread** runtime does so only while some thread sits inside
///   `Runtime::block_on` on it, and `Handle::block_on` is not that. With nobody
///   parked there, a handler that awaits any of those never completes and the
///   call never returns. A handler that needs none of them — ready on the first
///   poll, or suspending only on `yield_now` — still completes.
///
/// [`spawn_blocking`](tokio::task::spawn_blocking) is deliberately not in that
/// set: the blocking pool runs independently of the scheduler, so awaiting one
/// completes here too. An *outbound* call or lookup the handler makes itself
/// needs neither: on the handler's thread it runs inline (see
/// [`BinderAsyncPool`]), so it works from a handler this adapter is driving
/// on a current-thread handle, even though a `tokio::spawn`ed task in the same
/// place would not.
///
/// # Cost
///
/// A call from a **worker** thread releases that worker's core for the duration
/// and offers it to the `spawn_blocking` pool. From every other position nothing
/// is released and the call runs inline. The pool spawns a thread on demand, so
/// the core is only left unclaimed when the pool is at its
/// `max_blocking_threads` cap with every thread busy; then the call still
/// completes, but a runtime with a *single* worker runs nothing else until it
/// returns. A second worker, or headroom under the cap, removes that.
///
/// So on a path that calls a local async service repeatedly, convert the handle
/// once with [`Strong::into_async`] and await it instead — that route dispatches
/// to the async service directly and never enters `block_on`.
///
/// [`Handle`]: tokio::runtime::Handle
/// [`LocalSet`]: tokio::task::LocalSet
/// [`Strong::into_async`]: crate::Strong::into_async
pub struct TokioRuntime<R>(pub R);

impl BinderAsyncRuntime for TokioRuntime<tokio::runtime::Handle> {
    fn block_on<F: Future>(&self, future: F) -> F::Output {
        match tokio::runtime::Handle::try_current() {
            // Multi-thread: `block_in_place` frees a worker's core; inline on its blocking threads.
            Ok(handle) if handle.runtime_flavor() == tokio::runtime::RuntimeFlavor::MultiThread => {
                tokio::task::block_in_place(|| self.0.block_on(future))
            }
            // No runtime, or current-thread: panics only inside it; its blocking pool may block.
            _ => self.0.block_on(future),
        }
    }
}

